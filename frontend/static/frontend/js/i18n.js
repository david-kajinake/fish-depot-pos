let activeLanguage = 'en';
const translatedAttributes = ['placeholder', 'title', 'aria-label', 'button','p'];
const originalText = new WeakMap();
const originalAttributes = new WeakMap();

function translate(value) {
    return catalogue[activeLanguage]?.[value] || value;
}

function translateTextNode(node) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const original = originalText.get(node);
    const compact = original.trim();
    if (!compact) return;
    node.nodeValue = activeLanguage === 'en' ? original : original.replace(compact, translate(compact));
}

function translateElement(element) {
    if (element.closest('script, style, code, pre, [data-no-i18n]')) return;
    for (const attribute of translatedAttributes) {
        if (!element.hasAttribute(attribute)) continue;
        if (!originalAttributes.has(element)) originalAttributes.set(element, {});
        const attributes = originalAttributes.get(element);
        if (!(attribute in attributes)) attributes[attribute] = element.getAttribute(attribute);
        element.setAttribute(attribute, activeLanguage === 'en' ? attributes[attribute] : translate(attributes[attribute]));
    }
    for (const node of element.childNodes) {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
    }
}

function translateDocument(root = document.body) {
    if (!root) return;
    if (root.nodeType === Node.ELEMENT_NODE) translateElement(root);
    root.querySelectorAll?.('*').forEach(translateElement);
}

export function applyLanguage(language) {
    activeLanguage = catalogue[language] ? language : 'en';
    document.documentElement.lang = activeLanguage === 'sw' ? 'sw' : activeLanguage;
    translateDocument();
    window.dispatchEvent(new CustomEvent('languageApplied', { detail: { language: activeLanguage } }));
}

document.addEventListener('DOMContentLoaded', async () => {
    try {
        const response = await apiFetch('/api/settings/user/me/');
        if (response.ok) applyLanguage((await response.json()).language || 'en');
    } catch (error) {
        console.error('Unable to load language preference:', error);
    }
    const observer = new MutationObserver((mutations) => {
        for (const mutation of mutations) {
            mutation.addedNodes.forEach((node) => {
                if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
                if (node.nodeType === Node.ELEMENT_NODE) translateDocument(node);
            });
        }
    });
    observer.observe(document.body, { childList: true, subtree: true });
});
